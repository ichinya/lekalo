const planIdOf = (entries) => "plan-" + sha256Hex(canonicalJson(entries));

function canonicalJson(value) {
  if (value === undefined) return undefined;
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  if (value !== null && typeof value === "object") {
    const body = Object.keys(value)
      .filter((key) => value[key] !== undefined)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`)
      .join(",");
    return `{${body}}`;
  }
  return JSON.stringify(value);
}

const written = [];
function writeWire(family, name, envelopeOrText) {
  const text = typeof envelopeOrText === "string" ? envelopeOrText : canonicalJson(envelopeOrText);
  emit(`${family}/${name}.json`, text);
}
function writeDoc(family, name, value) {
  emit(`${family}/${name}.json`, `${JSON.stringify(value, null, 2)}\n`);
}
function writeExpect(name, expectation) {
  emit(`invalid/${name}.expect.json`, canonicalJson(expectation));
}
function emit(relative, text) {
  const target = join(CORPUS, relative);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, text);
  written.push(`tests/fixtures/adapter-sdk/${relative}`);
}

