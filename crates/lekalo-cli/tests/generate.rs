//! CLI integration tests for `lekalo generate` (issue #21): the read-only
//! drift gate, the preview/confirm clean flow, and the accepted exit
//! envelope. Every test runs the real binary over a sandbox project;
//! temp roots stay under `target/` addressed with relative selectors —
//! the Windows 8.3-alias lesson — and binary invocations go through
//! `alias_free_path`.

use serde_json::{json, Value};
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicU32, Ordering};

use lekalo_core::artifacts::GenerateService;
use lekalo_core::loader::LoadSelection;
use lekalo_core::versioning::plan::sha256_hex;

const REFERENCE_PROJECT: &str = "../../tests/fixtures/artifacts/project";
const ARTIFACT_DIR: &str = "apps/api/src/planner";
const ARTIFACT_NAME: &str = "focus-task.ts";
const ARTIFACT_CONTENT: &str = "export function focusTask() {\n  return planner.createTask();\n}\n";
const ORPHAN_CONTENT: &str = "orphaned generated bytes\n";

// GitHub Windows runners export %TEMP% as C:\Users\RUNNER~1\...; the
// selection policy denies alias spellings, so the real binary is always
// invoked from an alias-free working directory.
fn alias_free_path(path: &Path) -> PathBuf {
    let canonical = path.canonicalize().expect("canonicalize path");
    #[cfg(windows)]
    {
        let text = canonical.to_string_lossy().to_string();
        if let Some(stripped) = text.strip_prefix(r"\\?\") {
            if stripped.as_bytes().get(1) == Some(&b':') {
                return PathBuf::from(stripped);
            }
        }
    }
    canonical
}

fn stdout_text(output: &Output) -> String {
    String::from_utf8(output.stdout.clone()).expect("utf8 stdout")
}

fn stderr_text(output: &Output) -> String {
    String::from_utf8(output.stderr.clone()).expect("utf8 stderr")
}

fn exit_code(output: &Output) -> i32 {
    output.status.code().expect("exit code")
}

fn lekalo_in(dir: &Path, args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_lekalo"))
        .args(args)
        .current_dir(alias_free_path(dir))
        .env_remove("LEKALO_PROJECT")
        .output()
        .expect("run the real lekalo binary")
}

static NEXT_SANDBOX: AtomicU32 = AtomicU32::new(0);

fn copy_dir(from: &Path, to: &Path) {
    std::fs::create_dir_all(to).expect("create sandbox dir");
    for entry in std::fs::read_dir(from).expect("read reference") {
        let entry = entry.expect("reference entry");
        let target = to.join(entry.file_name());
        if entry.file_type().expect("entry type").is_dir() {
            copy_dir(&entry.path(), &target);
        } else {
            std::fs::copy(entry.path(), &target).expect("copy reference file");
        }
    }
}

struct Sandbox {
    root: PathBuf,
    selector: String,
}

impl Drop for Sandbox {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.root);
    }
}

fn with_sandbox(name: &str, body: impl FnOnce(&Sandbox)) {
    let id = NEXT_SANDBOX.fetch_add(1, Ordering::SeqCst);
    let relative = format!("target/generate-tests/{name}-{}-{id}", std::process::id());
    // The test process cwd is the crate dir, and the core selection APIs
    // resolve relative selectors from it: keep the sandbox under the
    // (git-ignored) crate-local target tree so both agree.
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(&relative);
    let _ = std::fs::remove_dir_all(&root);
    copy_dir(Path::new(REFERENCE_PROJECT), &root);
    let sandbox = Sandbox {
        selector: relative.replace('\\', "/"),
        root,
    };
    body(&sandbox);
    // Drop removes the tree even when the test panics, so a failed run
    // can never leak a sandbox project into other suites' scans.
    drop(sandbox);
}

impl Sandbox {
    fn selection(&self) -> LoadSelection {
        LoadSelection {
            project: Some(self.selector.clone()),
        }
    }

    fn create_lock(&self) {
        let output = lekalo_in(&self.root, &["lock"]);
        assert_eq!(exit_code(&output), 0, "{}", stderr_text(&output));
    }

    fn write_artifact(&self, name: &str, content: &str) {
        let dir = self.root.join(ARTIFACT_DIR);
        std::fs::create_dir_all(&dir).expect("artifact dir");
        std::fs::write(dir.join(name), content).expect("artifact bytes");
    }

    fn write_orphan(&self) -> String {
        let path = self.root.join(".lekalo/generated/scratch.txt");
        std::fs::create_dir_all(path.parent().expect("generated parent")).expect("dir");
        std::fs::write(&path, ORPHAN_CONTENT).expect("orphan bytes");
        ".lekalo/generated/scratch.txt".to_owned()
    }

    fn author_manifest(&self, artifacts: Vec<Value>) {
        let inputs = GenerateService::inputs(&self.selection()).expect("inputs receipt");
        let mut document = json!({
            "schema_version": "lekalo/artifact-manifest/v1.0.0",
            "identity": "dev.lekalo.artifact-manifest@1.0.0",
            "project_ref": "planner",
            "lock_ref": {
                "schema_version": "lekalo/lock/v1.0.0",
                "digest": inputs.lock_digest,
            },
            "inputs": {
                "model": {"version": inputs.model_version, "digest": inputs.model_digest},
                "ir": {"version": inputs.ir_version, "digest": inputs.ir_digest},
            },
            "artifacts": artifacts,
            "source_maps": [],
        });
        let mut draft = document.clone();
        draft
            .as_object_mut()
            .expect("object")
            .remove("manifest_digest");
        document["manifest_digest"] = json!(format!(
            "sha256:{}",
            sha256_hex(&serde_json::to_vec(&draft).expect("wire"))
        ));
        let path = self.root.join(".lekalo/generated/manifests/ownership.json");
        std::fs::create_dir_all(path.parent().expect("manifest parent")).expect("manifest dir");
        std::fs::write(
            &path,
            serde_json::to_vec(&document).expect("canonical wire"),
        )
        .expect("manifest bytes");
    }

    /// A full directory snapshot: sorted (relative path, size, sha256)
    /// lines. Read-only commands must never change it.
    fn snapshot(&self) -> String {
        let mut lines = Vec::new();
        fn walk(dir: &Path, base: &Path, lines: &mut Vec<String>) {
            for entry in std::fs::read_dir(dir).expect("read dir") {
                let entry = entry.expect("entry");
                let path = entry.path();
                let relative = path
                    .strip_prefix(base)
                    .expect("relative")
                    .to_string_lossy()
                    .replace('\\', "/");
                if path.is_dir() {
                    walk(&path, base, lines);
                } else {
                    let bytes = std::fs::read(&path).expect("read");
                    lines.push(format!(
                        "{} {} {}",
                        relative,
                        bytes.len(),
                        sha256_hex(&bytes)
                    ));
                }
            }
        }
        walk(&self.root, &self.root, &mut lines);
        lines.sort();
        lines.join("\n")
    }
}

fn artifact_value(owner: &str, path: &str, content: &str) -> Value {
    json!({
        "semantic_owner": owner,
        "path": path,
        "artifact_kind": "source",
        "lifecycle": "generated",
        "content": {
            "algorithm": "sha256",
            "digest": format!("sha256:{}", sha256_hex(content.as_bytes())),
            "canonicalization": "exact-file-bytes",
        },
        "input_refs": [owner],
        "regeneration_policy": "on-input-change",
    })
}

