#[test]
fn check_on_a_bound_manifest_is_clean_in_both_projections_and_deterministic() {
    with_sandbox("clean", |sandbox| {
        sandbox.create_lock();
        sandbox.write_artifact(ARTIFACT_NAME, ARTIFACT_CONTENT);
        sandbox.author_manifest(vec![artifact_value(
            "planner.create_task",
            "apps/api/src/planner/focus-task.ts",
            ARTIFACT_CONTENT,
        )]);
        let first = lekalo_in(&sandbox.root, &["generate", "--check"]);
        assert_eq!(exit_code(&first), 0, "{}", stderr_text(&first));
        let second = lekalo_in(&sandbox.root, &["generate", "--check"]);
        assert_eq!(stdout_text(&first), stdout_text(&second));
        // The human projection is one stable line.
        assert!(stdout_text(&first).starts_with("generate check clean manifest sha256:"));
        // The JSON projection carries the same verdict and counts.
        let json = lekalo_in(&sandbox.root, &["--json", "generate", "--check"]);
        assert_eq!(exit_code(&json), 0);
        let document: Value = serde_json::from_str(stdout_text(&json).trim()).expect("envelope");
        assert_eq!(document["status"], "valid");
        assert_eq!(document["mode"], "check");
        assert_eq!(document["verdict"], "clean");
        assert_eq!(document["counts"]["artifacts"], 1);
        assert_eq!(document["counts"]["clean"], 1);
    });
}

#[test]
fn check_writes_nothing_to_the_project_tree() {
    with_sandbox("readonly", |sandbox| {
        sandbox.create_lock();
        sandbox.write_artifact(ARTIFACT_NAME, ARTIFACT_CONTENT);
        sandbox.author_manifest(vec![artifact_value(
            "planner.create_task",
            "apps/api/src/planner/focus-task.ts",
            ARTIFACT_CONTENT,
        )]);
        let before = sandbox.snapshot();
        let output = lekalo_in(&sandbox.root, &["generate", "--check"]);
        assert_eq!(exit_code(&output), 0, "{}", stderr_text(&output));
        assert_eq!(sandbox.snapshot(), before, "generate --check wrote nothing");
    });
}

#[test]
fn manual_drift_blocks_with_exit_one_and_the_stable_rule_on_stderr() {
    with_sandbox("drift", |sandbox| {
        sandbox.create_lock();
        sandbox.write_artifact(ARTIFACT_NAME, ARTIFACT_CONTENT);
        sandbox.author_manifest(vec![artifact_value(
            "planner.create_task",
            "apps/api/src/planner/focus-task.ts",
            ARTIFACT_CONTENT,
        )]);
        sandbox.write_artifact(ARTIFACT_NAME, "export const drifted = true;\n");
        let human = lekalo_in(&sandbox.root, &["generate", "--check"]);
        assert_eq!(exit_code(&human), 1);
        assert!(stderr_text(&human).starts_with("invalid error [LEK-LOCK-018] lock.source-changed"));
        assert!(!stdout_text(&human).contains("LEK-LOCK-018"));
        let json = lekalo_in(&sandbox.root, &["--json", "generate", "--check"]);
        assert_eq!(exit_code(&json), 1);
        assert!(stderr_text(&json).contains("\"id\": \"lock.source-changed\""));
    });
}

#[test]
fn absent_lock_and_bare_generate_map_to_the_stable_failures() {
    with_sandbox("usage", |sandbox| {
        // A bare generate selects no mode: stable usage failure.
        let output = lekalo_in(&sandbox.root, &["generate"]);
        assert_eq!(exit_code(&output), 1);
        assert!(stderr_text(&output).contains("cli.usage"));
        // Mutually exclusive modes never fall through to clap's exit.
        let output = lekalo_in(&sandbox.root, &["generate", "--check", "--clean"]);
        assert_eq!(exit_code(&output), 1);
        assert!(stderr_text(&output).contains("cli.usage"));
        // The manifest binds the exact lock revision: no lock, no check.
        let output = lekalo_in(&sandbox.root, &["generate", "--check"]);
        assert_eq!(exit_code(&output), 1);
        assert!(stderr_text(&output).contains("lock.missing"));
    });
}

#[test]
fn an_unsupported_manifest_discriminator_maps_to_exit_five() {
    with_sandbox("future", |sandbox| {
        sandbox.create_lock();
        let path = sandbox
            .root
            .join(".lekalo/generated/manifests/ownership.json");
        std::fs::create_dir_all(path.parent().expect("parent")).expect("dir");
        std::fs::write(
            &path,
            "{\"schema_version\":\"lekalo/artifact-manifest/v9.0.0\"}\n",
        )
        .expect("future manifest");
        let output = lekalo_in(&sandbox.root, &["generate", "--check"]);
        assert_eq!(exit_code(&output), 5);
        assert!(stderr_text(&output).starts_with("unsupported-version error [LEK-LOCK-020]"));
    });
}

