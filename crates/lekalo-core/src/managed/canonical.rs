//! The deterministic managed renderer (issue #41).
//!
//! The generation function is `G(pinned closure, coverage) -> exact file
//! bytes`: fixed UTF-8 with LF endings, sorted fields, no wall clock, no
//! host paths, no ambient environment. The renderer reads only admitted
//! coverage descriptors; it never reads previous implementation sources.

use super::diagnostic;
use super::wire::{
    ArtifactRole, Coverage, ExtensionCheck, Reference, Requirement, Sample, Scalar, Support,
    MAX_BYTES,
};
use super::{detail, DomainResult, INPUT_INVALID};

/// The byte budget of one rendered artifact.
pub const RENDER_LIMIT: usize = MAX_BYTES;

/// One rendered output awaiting inventory classification.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Rendered {
    pub path: String,
    pub role: ArtifactRole,
    pub bytes: Vec<u8>,
}

fn invalid(reason: &str) -> DomainResult {
    diagnostic::failure(INPUT_INVALID, &detail(reason))
}

/// The requirement-local name: `<module>.<name>` yields `name`.
pub fn requirement_name<'a>(module: &str, requirement_id: &'a str) -> Option<&'a str> {
    let rest = requirement_id.strip_prefix(module)?;
    let name = rest.strip_prefix('.')?;
    if name.is_empty() || !name.bytes().all(|c| c.is_ascii_alphanumeric() || c == b'_') {
        return None;
    }
    Some(name)
}

/// `focus_task` renders as `focusTask`; snake case is the ledger spelling.
pub fn camel(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut upper = false;
    for character in name.chars() {
        if character == '_' {
            upper = true;
        } else if upper {
            out.extend(character.to_uppercase());
            upper = false;
        } else {
            out.push(character);
        }
    }
    out
}

/// `focus_task` renders as `focus-task`: the artifact file spelling (the
/// accepted artifact path policy only admits portable lowercase names).
pub fn file_stem(name: &str) -> String {
    name.replace('_', "-")
}

/// `focus_task` renders as `FocusTask` for type names.
pub fn pascal(name: &str) -> String {
    let camel = camel(name);
    let mut characters = camel.chars();
    match characters.next() {
        Some(first) => first.to_uppercase().collect::<String>() + characters.as_str(),
        None => camel,
    }
}

fn ts_type(value: &Scalar) -> &'static str {
    match value {
        Scalar::Flag(_) => "boolean",
        Scalar::Count(_) => "number",
        Scalar::Text(_) => "string",
        Scalar::Nothing => "null",
    }
}

fn json_literal(value: &Scalar) -> String {
    serde_json::to_value(value).expect("scalar").to_string()
}

fn record_literal(fields: &std::collections::BTreeMap<String, Scalar>) -> String {
    let members: Vec<String> = fields
        .iter()
        .map(|(key, value)| format!("{key}: {}", json_literal(value)))
        .collect();
    format!("{{ {} }}", members.join(", "))
}

fn header_comment(
    recipe: &Reference,
    module: &str,
    target: &str,
    requirement: &Requirement,
) -> String {
    format!(
        "// Generated by lekalo managed generation; do not edit.\n\
         // Recipe: {id}@{version} ({digest})\n\
         // Module: {module}; target: {target}; requirement: {requirement}.\n\
         // Source of truth: the pinned Lekalo Model inputs of this generation.\n",
        id = recipe.id,
        version = recipe.version,
        digest = recipe.digest,
        module = module,
        target = target,
        requirement = requirement.id,
    )
}

/// The implementation and test file names of one admitted requirement.
pub fn output_paths(
    generated_root: &str,
    module: &str,
    requirement: &Requirement,
) -> Option<(String, String)> {
    let name = requirement_name(module, &requirement.id)?;
    let stem = file_stem(name);
    Some((
        format!("{generated_root}/src/{stem}.ts"),
        format!("{generated_root}/test/{stem}.test.ts"),
    ))
}

fn field_type(
    requirement: &Requirement,
    side: fn(&Sample) -> &std::collections::BTreeMap<String, Scalar>,
    field: &str,
) -> String {
    requirement
        .sample
        .value()
        .and_then(|sample| side(sample).get(field))
        .map(|value| ts_type(value).to_owned())
        .unwrap_or_else(|| "unknown".to_owned())
}

fn render_implementation(
    recipe: &Reference,
    module: &str,
    target: &str,
    requirement: &Requirement,
) -> Result<Vec<u8>, DomainResult> {
    let name =
        requirement_name(module, &requirement.id).ok_or_else(|| invalid("requirement-name"))?;
    let function = camel(name);
    let types = pascal(name);
    let mut input_fields = String::new();
    let mut output_fields = String::new();
    let returns: Vec<String> = requirement
        .projection
        .iter()
        .map(|projection| {
            format!(
                "{to}: input.{from}",
                to = projection.to,
                from = projection.from
            )
        })
        .collect();
    for projection in &requirement.projection {
        input_fields.push_str(&format!(
            "  {field}: {kind};\n",
            field = projection.from,
            kind = field_type(requirement, |sample| &sample.input, &projection.from)
        ));
        output_fields.push_str(&format!(
            "  {field}: {kind};\n",
            field = projection.to,
            kind = field_type(requirement, |sample| &sample.output, &projection.to)
        ));
    }
    let document = format!(
        "{header}\n\
         export interface {types}Input {{\n{input_fields}}}\n\
         \n\
         export interface {types}Output {{\n{output_fields}}}\n\
         \n\
         export function {function}(input: {types}Input): {types}Output {{\n  return {{\n    {returns},\n  }};\n}}\n",
        header = header_comment(recipe, module, target, requirement),
        types = types,
        input_fields = input_fields,
        output_fields = output_fields,
        function = function,
        returns = returns.join(",\n    "),
    );
    Ok(document.into_bytes())
}

fn render_test(
    recipe: &Reference,
    module: &str,
    target: &str,
    requirement: &Requirement,
    extensions: &[ExtensionCheck],
    generated_root: &str,
) -> Result<Vec<u8>, DomainResult> {
    let name =
        requirement_name(module, &requirement.id).ok_or_else(|| invalid("requirement-name"))?;
    let function = camel(name);
    let sample = requirement
        .sample
        .value()
        .ok_or_else(|| diagnostic::failure(super::CAPABILITY_GAP, &detail("sample")))?;
    let mut document = header_comment(recipe, module, target, requirement);
    document.push_str(&format!(
        "// Behavioral evidence: the generated handler is invoked directly.\n\
         // Expected values are the pinned scenario sample of this recipe.\n\
         \n\
         import assert from \"node:assert/strict\";\n\
         import {{ {function} }} from \"../src/{file}.ts\";\n",
        function = function,
        file = file_stem(name),
    ));
    // Every resolved custom/foreign binding is invoked explicitly: the
    // generated evidence proves the pinned implementation is live for
    // this generation (finding K).
    for extension in extensions {
        if !extension.validated {
            continue;
        }
        let Some((binding_file, binding_symbol)) = binding_parts(&extension.binding) else {
            return Err(invalid("binding"));
        };
        let Some(relative) = relative_binding_path(generated_root, &binding_file) else {
            return Err(invalid("binding"));
        };
        document.push_str(&format!(
            "import {{ {binding_symbol} }} from \"{relative}\";\n",
        ));
    }
    document.push_str(&format!(
        "\nassert.deepStrictEqual(\n  {function}({input}),\n  {output},\n);\n",
        function = function,
        input = record_literal(&sample.input),
        output = record_literal(&sample.output),
    ));
    for extension in extensions {
        if !extension.validated {
            continue;
        }
        let symbol = extension
            .binding
            .split('#')
            .nth(1)
            .unwrap_or(&extension.symbol);
        let invoked = camel(symbol);
        document.push_str(&format!(
            "assert.strictEqual(typeof {invoked}, \"function\");\n\
             assert.ok({invoked}({{}}) !== undefined);\n",
        ));
    }
    Ok(document.into_bytes())
}

/// The file and exported symbol of one binding spelling
/// (`path/file.ts` or `path/file.ts#symbol`).
fn binding_parts(binding: &str) -> Option<(String, String)> {
    let (file, symbol) = match binding.split_once('#') {
        Some((file, symbol)) => (file, symbol),
        None => (binding, "default"),
    };
    if file.is_empty() || symbol.is_empty() {
        return None;
    }
    Some((file.to_owned(), symbol.to_owned()))
}

/// The import specifier of one project-relative binding file as seen from
/// the generated test directory `<generated_root>/test/`.
fn relative_binding_path(generated_root: &str, binding_file: &str) -> Option<String> {
    let from_dir = format!("{generated_root}/test");
    let from: Vec<&str> = from_dir.split('/').collect();
    let to: Vec<&str> = binding_file.split('/').collect();
    let mut common = 0usize;
    while common < from.len() && common < to.len() && from[common] == to[common] {
        common += 1;
    }
    let mut parts: Vec<String> = from[common..].iter().map(|_| "..".to_owned()).collect();
    parts.extend(to[common..].iter().map(|segment| segment.to_string()));
    if parts.is_empty() {
        return None;
    }
    Some(parts.join("/"))
}

/// Render the complete deterministic output inventory of one admitted
/// coverage document under one generated root. Output order is the fixed
/// path byte order; every rendered artifact is bounded.
pub fn render_inventory(
    coverage: &Coverage,
    generated_root: &str,
) -> Result<Vec<Rendered>, DomainResult> {
    if !super::rel_path(generated_root) {
        return Err(invalid("generated-root"));
    }
    let mut rendered = Vec::new();
    for requirement in &coverage.requirements {
        if requirement.support != Support::Full || !requirement.kind.renders() {
            continue;
        }
        let (implementation, test) = output_paths(generated_root, &coverage.module, requirement)
            .ok_or_else(|| invalid("requirement-name"))?;
        let mut push = |path: String, role: ArtifactRole, bytes: Vec<u8>| {
            if bytes.len() > RENDER_LIMIT {
                return Err(invalid("render-bound"));
            }
            rendered.push(Rendered { path, role, bytes });
            Ok(())
        };
        push(
            implementation,
            ArtifactRole::Implementation,
            render_implementation(
                &coverage.recipe,
                &coverage.module,
                &coverage.target,
                requirement,
            )?,
        )?;
        push(
            test,
            ArtifactRole::Test,
            render_test(
                &coverage.recipe,
                &coverage.module,
                &coverage.target,
                requirement,
                &coverage.extensions,
                generated_root,
            )?,
        )?;
    }
    Ok(rendered)
}
