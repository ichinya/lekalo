#[test]
fn artifact_paths_from_the_wire_pass_the_accepted_path_policy() {
    // Absolute, traversal, device, and backslash spellings can never form
    // an ArtifactPath, so a manifest carrying them is a shape refusal.
    with_project(|sandbox| {
        sandbox.create_lock();
        for hostile in [
            "/etc/passwd",
            "../outside.ts",
            "apps/api/C:\\evil.ts",
            "apps/api/CON.ts",
        ] {
            let _ = std::fs::remove_file(sandbox.manifest_path());
            let _ = sandbox.write_artifact(ARTIFACT_CONTENT);
            author_manifest(
                sandbox,
                vec![artifact_value(
                    "planner.create_task",
                    hostile,
                    "source",
                    "generated",
                    "",
                )],
                vec![],
            );
            let failure = GenerateService::check(&sandbox.selection()).expect_err(hostile);
            assert!(
                matches!(failure, ArtifactFailure::ManifestInvalid)
                    || matches!(failure, ArtifactFailure::Structure { .. })
                    || matches!(failure, ArtifactFailure::Drift(_)),
                "hostile path {hostile} produced {failure:?}"
            );
        }
    });
}

