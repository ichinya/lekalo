#[test]
fn source_map_revision_and_range_bounds_fail_closed() {
    with_project(|sandbox| {
        sandbox.create_lock();
        let content = ARTIFACT_CONTENT.repeat(3);
        sandbox.write_artifact(&content);
        let inputs = GenerateService::inputs(&sandbox.selection()).expect("inputs");
        let good_map = json!({
            "artifact": {
                "semantic_owner": "planner.create_task",
                "path": "apps/api/src/planner/focus-task.ts",
                "artifact_kind": "source",
            },
            "input_revision": inputs.revision,
            "entries": [
                {"semantic_id": "planner.create_task", "start": 0, "end": 16},
                {"semantic_id": "planner.task", "start": 16, "end": 17},
            ],
        });
        author_manifest(
            sandbox,
            vec![artifact_value(
                "planner.create_task",
                "apps/api/src/planner/focus-task.ts",
                "source",
                "generated",
                &content,
            )],
            vec![good_map],
        );
        GenerateService::check(&sandbox.selection()).expect("valid map");

        // A foreign input revision refuses the whole map.
        let bytes = std::fs::read(sandbox.manifest_path()).expect("manifest");
        let mut document: Value = serde_json::from_slice(&bytes).expect("wire");
        document["source_maps"][0]["input_revision"] =
            json!(format!("sha256:{}", sha256_hex(b"foreign")));
        restamp_and_write(sandbox, &document);
        let failure = GenerateService::check(&sandbox.selection()).expect_err("foreign revision");
        assert_eq!(
            reason_codes(&failure),
            vec!["lock.reference-invalid".to_owned()]
        );

        // Re-author with a good revision and an out-of-range end instead.
        let inputs = GenerateService::inputs(&sandbox.selection()).expect("inputs");
        let bad_map = json!({
            "artifact": {
                "semantic_owner": "planner.create_task",
                "path": "apps/api/src/planner/focus-task.ts",
                "artifact_kind": "source",
            },
            "input_revision": inputs.revision,
            "entries": [{"semantic_id": "planner.create_task", "start": 0, "end": 999_999}],
        });
        author_manifest(
            sandbox,
            vec![artifact_value(
                "planner.create_task",
                "apps/api/src/planner/focus-task.ts",
                "source",
                "generated",
                &content,
            )],
            vec![bad_map],
        );
        let failure = GenerateService::check(&sandbox.selection()).expect_err("range bound");
        assert_eq!(
            reason_codes(&failure),
            vec!["lock.reference-invalid".to_owned()]
        );
    });
}

fn restamp_and_write(sandbox: &Sandbox, document: &Value) {
    let mut draft = document.clone();
    draft
        .as_object_mut()
        .expect("object")
        .remove("manifest_digest");
    let mut final_doc = document.clone();
    final_doc["manifest_digest"] = json!(format!(
        "sha256:{}",
        sha256_hex(&serde_json::to_vec(&draft).expect("wire"))
    ));
    std::fs::write(
        sandbox.manifest_path(),
        serde_json::to_vec(&final_doc).expect("wire"),
    )
    .expect("rewrite");
}

