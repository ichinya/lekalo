//! Integration tests for the generated-artifact ownership manifest and
//! drift detection (issue #21). Every test runs the real pipeline over a
//! numbered sandbox under `target/` addressed with a relative selector —
//! never a canonicalized temp path, which the accepted selection policy
//! denies on Windows (the 8.3-alias lesson).

use serde_json::{json, Value};
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU32, Ordering};

use lekalo_core::artifacts::{
    ArtifactFailure, DriftVerdict, GenerateService, GENERATED_ROOT, MANIFEST_DIR, MANIFEST_NAME,
};
use lekalo_core::loader::LoadSelection;
use lekalo_core::lockfile::plan::LockService;
use lekalo_core::lockfile::resolution::CandidateSet;
use lekalo_core::lockfile::LockRequirement;
use lekalo_core::versioning::plan::sha256_hex;

const REFERENCE_PROJECT: &str = "../../tests/fixtures/artifacts/project";
const ARTIFACT_DIR: &str = "apps/api/src/planner";
const ARTIFACT_NAME: &str = "focus-task.ts";
const ARTIFACT_CONTENT: &str = "export function focusTask() {\n  return planner.createTask();\n}\n";

static NEXT_ROOT: AtomicU32 = AtomicU32::new(0);

struct Sandbox {
    selector: String,
    root: PathBuf,
}

impl Drop for Sandbox {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.root);
    }
}

fn copy_dir(from: &Path, to: &Path) {
    std::fs::create_dir_all(to).expect("create sandbox dir");
    for entry in std::fs::read_dir(from).expect("read reference") {
        let entry = entry.expect("reference entry");
        let target = to.join(entry.file_name());
        if entry.file_type().expect("entry type").is_dir() {
            copy_dir(&entry.path(), &target);
        } else {
            std::fs::copy(entry.path(), &target).expect("copy reference file");
        }
    }
}

fn with_project(body: impl FnOnce(&Sandbox)) {
    let id = NEXT_ROOT.fetch_add(1, Ordering::SeqCst);
    let relative = format!("target/artifact-tests/case-{}-{}", std::process::id(), id);
    let root = PathBuf::from(&relative);
    let _ = std::fs::remove_dir_all(&root);
    copy_dir(Path::new(REFERENCE_PROJECT), &root);
    let sandbox = Sandbox {
        selector: relative.replace('\\', "/"),
        root,
    };
    body(&sandbox);
    // Drop also removes the tree when the test panics: a leftover
    // sandbox project must never leak into other suites' scans.
    drop(sandbox);
}

impl Sandbox {
    fn selection(&self) -> LoadSelection {
        LoadSelection {
            project: Some(self.selector.clone()),
        }
    }

    fn create_lock(&self) -> String {
        let receipt = LockService::lock(
            &self.selection(),
            CandidateSet::empty(),
            LockRequirement::Optional,
            true,
        )
        .expect("lock created");
        assert_eq!(receipt.mode, "create");
        receipt.lock_digest
    }

    fn write_artifact(&self, content: &str) -> String {
        let dir = self.root.join(ARTIFACT_DIR);
        std::fs::create_dir_all(&dir).expect("artifact dir");
        std::fs::write(dir.join(ARTIFACT_NAME), content).expect("artifact bytes");
        lekalo_core::versioning::plan::sha256_hex(content.as_bytes())
    }

    fn manifest_path(&self) -> PathBuf {
        self.root.join(MANIFEST_DIR).join(MANIFEST_NAME)
    }

    fn write_generated(&self, content: &str) -> String {
        let path = self.root.join(GENERATED_ROOT).join("scratch.txt");
        std::fs::create_dir_all(path.parent().expect("generated parent")).expect("generated dir");
        std::fs::write(&path, content).expect("generated bytes");
        ".lekalo/generated/scratch.txt".to_owned()
    }
}

/// One closed wire artifact entry with the exact digest of `content`.
fn artifact_value(owner: &str, path: &str, kind: &str, lifecycle: &str, content: &str) -> Value {
    let policy = match lifecycle {
        "generated" => "on-input-change",
        "scaffolded" => "once",
        "checked" => "validate-only",
        "external" => "reference-only",
        _ => "manual-only",
    };
    json!({
        "semantic_owner": owner,
        "path": path,
        "artifact_kind": kind,
        "lifecycle": lifecycle,
        "content": {
            "algorithm": "sha256",
            "digest": format!("sha256:{}", sha256_hex(content.as_bytes())),
            "canonicalization": "exact-file-bytes",
        },
        "input_refs": [owner],
        "regeneration_policy": policy,
    })
}

/// One adapter-bound entry: refused against a lock whose target protocol
/// is still unpublished.
fn adapter_bound_value(owner: &str, path: &str, content: &str) -> Value {
    let mut entry = artifact_value(owner, path, "source", "generated", content);
    entry["adapter_ref"] = json!({
        "id": "node-typescript",
        "version": "0.1.2",
        "digest": format!("sha256:{}", sha256_hex(b"adapter-package")),
        "artifacts": [{"platform": "any", "digest": format!("sha256:{}", sha256_hex(b"adapter-any"))}],
        "protocol_version": null,
    });
    entry["generator_ref"] = json!({"id": "planner-gen", "version": "0.3.0"});
    entry
}

/// Author the canonical manifest for one sandbox from the live inputs.
fn author_manifest(sandbox: &Sandbox, artifacts: Vec<Value>, source_maps: Vec<Value>) {
    let inputs = GenerateService::inputs(&sandbox.selection()).expect("inputs receipt");
    let mut document = json!({
        "schema_version": "lekalo/artifact-manifest/v1.0.0",
        "identity": "dev.lekalo.artifact-manifest@1.0.0",
        "project_ref": "planner",
        "lock_ref": {
            "schema_version": "lekalo/lock/v1.0.0",
            "digest": inputs.lock_digest,
        },
        "inputs": {
            "model": {"version": inputs.model_version, "digest": inputs.model_digest},
            "ir": {"version": inputs.ir_version, "digest": inputs.ir_digest},
        },
        "artifacts": artifacts,
        "source_maps": source_maps,
    });
    // Stamp the non-self-referential digest over the payload without it.
    let stamp = |document: &Value| -> String {
        let mut draft = document.clone();
        draft
            .as_object_mut()
            .expect("object")
            .remove("manifest_digest");
        format!(
            "sha256:{}",
            sha256_hex(&serde_json::to_vec(&draft).expect("wire"))
        )
    };
    let digest = stamp(&document);
    document["manifest_digest"] = json!(digest);
    let path = sandbox.manifest_path();
    std::fs::create_dir_all(path.parent().expect("manifest parent")).expect("manifest dir");
    std::fs::write(
        &path,
        serde_json::to_vec(&document).expect("canonical wire"),
    )
    .expect("manifest bytes");
}

/// Overwrite the manifest keeping its declared digest (integrity tamper).
fn tamper_manifest_digest(sandbox: &Sandbox) {
    let bytes = std::fs::read(sandbox.manifest_path()).expect("manifest");
    let mut document: Value = serde_json::from_slice(&bytes).expect("wire");
    document["inputs"]["ir"]["digest"] = json!(format!("sha256:{}", sha256_hex(b"other")));
    std::fs::write(
        sandbox.manifest_path(),
        serde_json::to_vec(&document).expect("wire"),
    )
    .expect("rewrite");
}

fn reason_codes(failure: &ArtifactFailure) -> Vec<String> {
    let result = lekalo_core::DomainResult::from(failure);
    result
        .reason_codes()
        .iter()
        .map(|code| code.as_str().to_owned())
        .collect()
}

fn exit_of(failure: &ArtifactFailure) -> u8 {
    lekalo_core::DomainResult::from(failure).exit_code()
}

