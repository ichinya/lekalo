// The SDK generate example (issue #106): a generation adapter on the Go
// adapter SDK that opts into one narrow output scope, plans before
// apply, computes dry-run byte digests without writing, and echoes the
// host's plan authority on apply. Read-only by default.
package main

import (
	"os"
	"path/filepath"

	sdk "github.com/ichinya/lekalo-adapter-sdk-go/runtime"
)

const (
	adapterID = "sdk-generate-example"
	writeRoot = ".lekalo/generated"
)

type generateAdapter struct {
	identity    sdk.Value
	writeScopes []string
}

func deterministicWrites(request sdk.Value) (string, string, []any) {
	target := sdk.GetString(request, "target")
	if target == "" {
		target = adapterID
	}
	profile := sdk.GetString(request, "profile")
	if profile == "" {
		profile = "default"
	}
	irPath := sdk.GetString(request, "ir_path")
	if irPath == "" {
		irPath = ".lekalo/ir/planner.json"
	}
	body := "// generated by " + adapterID + "@0.1.0\n// target: " + target + "\n// profile: " + profile + "\n// ir: " + irPath + "\n"
	path := writeRoot + "/" + adapterID + "/model.ts"
	writes := []any{map[string]any{
		"action": "create",
		"path":   path,
		"sha256": sdk.WriteEntryDigest(body),
	}}
	return body, path, writes
}

func (a *generateAdapter) Identity() sdk.Value {
	return a.identity
}

func (a *generateAdapter) Handle(operation string, request sdk.Value) sdk.Output {
	switch operation {
	case "describe":
		capabilities, err := sdk.BuildCapabilities(
			a.identity,
			[]string{"0.3.2"},
			[]string{"describe", "generate", "plan-clean"},
			[]string{"file", "stdin"},
			[]string{adapterID},
			nil,
			[]string{".lekalo/ir/**"},
			a.writeScopes,
			[]string{"0.2.16"},
			true,
			map[string]string{"generate.zod": "full"},
			nil,
		)
		if err != nil {
			return refused()
		}
		return sdk.Output{Capabilities: capabilities}
	case "generate":
		body, modelPath, writes := deterministicWrites(request)
		for _, entry := range writes {
			entryObject := entry.(map[string]any)
			if violation := sdk.WritePlanViolation(entryObject["path"].(string), a.writeScopes); violation != "" {
				return sdk.Output{Error: [3]string{"invalid", "write-refused", "the write plan left the declared output scope: " + violation}, HasError: true}
			}
		}
		if dryRun, _ := sdk.GetBool(request, "dry_run"); !dryRun {
			_ = os.MkdirAll(filepath.Dir(modelPath), 0o755)
			_ = os.WriteFile(modelPath, []byte(body), 0o644)
		}
		planID := sdk.GetString(request, "plan_id")
		if planID == "" {
			planID = sdk.PlanID(writes)
		}
		return sdk.Output{
			PlanID:   planID,
			Progress: []any{map[string]any{"state": "done", "step": "emit"}},
			Writes:   writes,
		}
	case "plan-clean":
		_, _, writes := deterministicWrites(request)
		plan := make([]any, 0, len(writes))
		for _, entry := range writes {
			entryObject := entry.(map[string]any)
			plan = append(plan, map[string]any{"action": "delete", "path": entryObject["path"]})
		}
		return sdk.Output{PlanID: sdk.PlanID(plan), Writes: plan}
	default:
		return sdk.Output{Error: [3]string{"unsupported", "operation-unsupported", "the generate example implements describe, generate, and plan-clean only"}, HasError: true}
	}
}

func refused() sdk.Output {
	return sdk.Output{Error: [3]string{"infrastructure", "sdk-build-refused", "the capability builder refused the declaration"}, HasError: true}
}

func main() {
	identity, err := sdk.BuildAdapterIdentity(adapterID, "0.1.0", sdk.Sha256("lekalo adapter-sdk generate example"))
	if err != nil {
		os.Exit(1)
	}
	os.Exit(sdk.Serve(&generateAdapter{
		identity:    identity,
		writeScopes: []string{writeRoot + "/" + adapterID + "/**"},
	}))
}
