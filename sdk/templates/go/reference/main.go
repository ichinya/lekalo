// The SDK reference adapter (issue #106): the complete strict base
// surface implemented entirely on the Go adapter SDK, equivalent to the
// handwritten fake-adapter control but with every wire byte built,
// validated, and emitted by the SDK runtime. Deterministic.
package main

import (
	"os"
	"path/filepath"

	sdk "github.com/ichinya/lekalo-adapter-sdk-go/runtime"
)

const (
	adapterID = "sdk-reference"
	writeRoot = ".lekalo/generated"
)

type referenceAdapter struct {
	identity    sdk.Value
	writeScopes []string
}

func deterministicWrites(request sdk.Value) (string, string, []any) {
	target := sdk.GetString(request, "target")
	if target == "" {
		target = adapterID
	}
	profile := sdk.GetString(request, "profile")
	if profile == "" {
		profile = "default"
	}
	irPath := sdk.GetString(request, "ir_path")
	if irPath == "" {
		irPath = ".lekalo/ir/planner.json"
	}
	body := "// generated by " + adapterID + "@0.1.0\n// target: " + target + "\n// profile: " + profile + "\n// ir: " + irPath + "\n"
	path := writeRoot + "/" + adapterID + "/model.ts"
	writes := []any{map[string]any{
		"action": "create",
		"path":   path,
		"sha256": sdk.WriteEntryDigest(body),
	}}
	return body, path, writes
}

func planIDOf(writes []any) string {
	return sdk.PlanID(writes)
}

func (a *referenceAdapter) Identity() sdk.Value {
	return a.identity
}

func (a *referenceAdapter) Handle(operation string, request sdk.Value) sdk.Output {
	switch operation {
	case "bind":
		return sdk.Output{Payload: map[string]any{
			"bindings": []any{map[string]any{
				"module":  "planner",
				"profile": sdk.GetString(request, "profile"),
				"target":  sdk.GetString(request, "target"),
			}},
		}}
	case "clean":
		_, _, writes := deterministicWrites(request)
		plan := make([]any, 0, len(writes))
		for _, entry := range writes {
			entryObject := entry.(map[string]any)
			plan = append(plan, map[string]any{"action": "delete", "path": entryObject["path"]})
			if path, ok := entryObject["path"].(string); ok {
				_ = os.Remove(path)
			}
		}
		planID := sdk.GetString(request, "plan_id")
		if planID == "" {
			planID = planIDOf(plan)
		}
		return sdk.Output{PlanID: planID, Writes: plan}
	case "describe":
		capabilities, err := sdk.BuildCapabilities(
			a.identity,
			[]string{"0.3.2"},
			[]string{"bind", "clean", "describe", "generate", "plan-clean", "plan-native", "scan", "validate", "verify"},
			[]string{"file", "stdin"},
			[]string{adapterID},
			nil,
			[]string{".lekalo/ir/**", ".lekalo/cache/ir/**"},
			a.writeScopes,
			[]string{"0.2.16"},
			true,
			map[string]string{
				"generate.openapi": "partial",
				"generate.ui":      "unsupported",
				"generate.zod":     "full",
				"scan.symbols":     "full",
				"verify.scenarios": "full",
			},
			nil,
		)
		if err != nil {
			return refused()
		}
		return sdk.Output{Capabilities: capabilities}
	case "generate":
		body, modelPath, writes := deterministicWrites(request)
		for _, entry := range writes {
			entryObject := entry.(map[string]any)
			if violation := sdk.WritePlanViolation(entryObject["path"].(string), a.writeScopes); violation != "" {
				return sdk.Output{Error: [3]string{"invalid", "write-refused", "the write plan left the declared output scope: " + violation}, HasError: true}
			}
		}
		if dryRun, _ := sdk.GetBool(request, "dry_run"); !dryRun {
			_ = os.MkdirAll(filepath.Dir(modelPath), 0o755)
			_ = os.WriteFile(modelPath, []byte(body), 0o644)
		}
		planID := sdk.GetString(request, "plan_id")
		if planID == "" {
			planID = planIDOf(writes)
		}
		return sdk.Output{
			PlanID: planID,
			Progress: []any{
				map[string]any{"state": "done", "step": "compile"},
				map[string]any{"state": "done", "step": "emit"},
			},
			Writes: writes,
		}
	case "plan-clean":
		_, _, writes := deterministicWrites(request)
		plan := make([]any, 0, len(writes))
		for _, entry := range writes {
			entryObject := entry.(map[string]any)
			plan = append(plan, map[string]any{"action": "delete", "path": entryObject["path"]})
		}
		return sdk.Output{PlanID: planIDOf(plan), Writes: plan}
	case "plan-native":
		return sdk.Output{Error: [3]string{"unsupported", "plan-native-unsupported", "this reference adapter does not plan native gates"}, HasError: true}
	case "scan":
		return sdk.Output{Payload: map[string]any{
			"entries": []any{
				map[string]any{"kind": "source", "path": "src/main.ts"},
				map[string]any{"kind": "source", "path": "src/util.ts"},
			},
			"truncated": false,
		}}
	case "validate", "verify":
		return sdk.Output{Payload: map[string]any{"findings": []any{}, "ok": true}}
	default:
		return sdk.Output{Error: [3]string{"unsupported", "operation-unsupported", "the operation is not implemented by this adapter"}, HasError: true}
	}
}

func refused() sdk.Output {
	return sdk.Output{Error: [3]string{"infrastructure", "sdk-build-refused", "the capability builder refused the declaration"}, HasError: true}
}

func main() {
	identity, err := sdk.BuildAdapterIdentity(adapterID, "0.1.0", sdk.Sha256("lekalo adapter-sdk reference adapter"))
	if err != nil {
		os.Exit(1)
	}
	os.Exit(sdk.Serve(&referenceAdapter{
		identity:    identity,
		writeScopes: []string{writeRoot + "/" + adapterID + "/**"},
	}))
}
