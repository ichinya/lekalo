// The SDK reference adapter (issue #106): the complete strict base
// surface implemented entirely on the Go adapter SDK, equivalent to the
// handwritten fake-adapter control but with every wire byte built,
// validated, and emitted by the SDK runtime. Deterministic.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	sdk "github.com/ichinya/lekalo-adapter-sdk-go/runtime"
)

const (
	adapterID = "sdk-reference"
	writeRoot = ".lekalo/generated"
)

// fault reports whether the closed hostile-mode knob is active (issue
// #106 review r3 #1/#2): the same --lekalo-fault vocabulary as the
// handwritten fake-adapter control (crash, garbage, hang, noise,
// mutate-dry, extra-write), so the lifecycle lanes drive the hostile
// classes against the real SDK serve loop. A run without the flag is
// fully cooperative.
func fault(name string) bool {
	value := ""
	for index, argument := range os.Args {
		if argument == "--lekalo-fault" && index+1 < len(os.Args) {
			value = os.Args[index+1]
		}
	}
	for _, candidate := range strings.Split(value, ",") {
		if candidate == name {
			return true
		}
	}
	return false
}

type referenceAdapter struct {
	identity    sdk.Value
	writeScopes []string
}

// Deliberately invalid completed callback output for serve-level probes.
func mutateCapabilities(value sdk.Value) sdk.Value {
	caps := value.(map[string]any)
	for _, member := range []string{"operations", "protocol_versions", "transports"} {
		if fault("invalid-" + member) {
			caps[member] = []any{}
		}
	}
	for _, member := range []string{"max_entries", "max_writes"} {
		if fault("invalid-" + member) {
			caps["constraints"] = map[string]any{member: int64(0)}
		}
	}
	if fault("invalid-capability") {
		caps["capabilities"] = map[string]any{"not.a.real.capability": "full"}
	}
	if fault("invalid-identity") {
		identity := map[string]any{}
		for key, member := range caps["adapter"].(map[string]any) {
			identity[key] = member
		}
		identity["id"] = "foreign-adapter"
		caps["adapter"] = identity
	}
	if fault("invalid-negotiation") {
		caps["protocol_versions"] = []any{"9.9.9"}
	}
	if fault("invalid-describe") {
		caps["operations"] = []any{"scan"}
	}
	return caps
}

func deterministicWrites(request sdk.Value) (string, string, []any) {
	target := sdk.GetString(request, "target")
	if target == "" {
		target = adapterID
	}
	profile := sdk.GetString(request, "profile")
	if profile == "" {
		profile = "default"
	}
	irPath := sdk.GetString(request, "ir_path")
	if irPath == "" {
		irPath = ".lekalo/ir/planner.json"
	}
	body := "// generated by " + adapterID + "@0.1.0\n// target: " + target + "\n// profile: " + profile + "\n// ir: " + irPath + "\n"
	path := writeRoot + "/" + adapterID + "/model.ts"
	writes := []any{map[string]any{
		"action": "create",
		"path":   path,
		"sha256": sdk.WriteEntryDigest(body),
	}}
	return body, path, writes
}

func planIDOf(writes []any) string {
	return sdk.PlanID(writes)
}

func (a *referenceAdapter) Identity() sdk.Value {
	return a.identity
}

func (a *referenceAdapter) Handle(operation string, request sdk.Value) sdk.Output {
	// Honest callback-error and real handler-crash (panic) are separate.
	// The runtime recovers the panic to a nonzero, empty-stdout refusal.
	// callback-hang
	// stalls inside the handler past every deadline (host termination
	// while the serve loop is live), and log-verbose floods the bounded
	// SDK logger from inside the handler (a verbose run must still pass).
	if fault("log-verbose") {
		for index := 0; index < 200; index++ {
			sdk.Error(adapterID, fmt.Sprintf("verbose lifecycle tick %d (%s)", index, operation))
		}
	}
	if fault("callback-hang") {
		time.Sleep(60 * time.Second)
	}
	if fault("handler-crash") {
		panic("callback exploded inside the SDK serve loop")
	}
	if fault("callback-error") {
		return sdk.Output{Error: [3]string{"infrastructure", "callback-error", "the handler deliberately refused"}, HasError: true}
	}
	switch operation {
	case "bind":
		return sdk.Output{Payload: map[string]any{
			"bindings": []any{map[string]any{
				"module":  "planner",
				"profile": sdk.GetString(request, "profile"),
				"target":  sdk.GetString(request, "target"),
			}},
		}}
	case "clean":
		_, _, writes := deterministicWrites(request)
		plan := make([]any, 0, len(writes))
		for _, entry := range writes {
			entryObject := entry.(map[string]any)
			plan = append(plan, map[string]any{"action": "delete", "path": entryObject["path"]})
			if path, ok := entryObject["path"].(string); ok {
				_ = os.Remove(path)
			}
		}
		planID := sdk.GetString(request, "plan_id")
		if planID == "" {
			planID = planIDOf(plan)
		}
		return sdk.Output{PlanID: planID, Writes: plan}
	case "describe":
		capabilities, err := sdk.BuildCapabilities(
			a.identity,
			[]string{"0.3.2"},
			[]string{"bind", "clean", "describe", "generate", "plan-clean", "plan-native", "scan", "validate", "verify"},
			[]string{"file", "stdin"},
			[]string{adapterID},
			nil,
			[]string{".lekalo/ir/**", ".lekalo/cache/ir/**"},
			a.writeScopes,
			[]string{"0.2.16"},
			true,
			map[string]string{
				"generate.openapi": "partial",
				"generate.ui":      "unsupported",
				"generate.zod":     "full",
				"scan.symbols":     "full",
				"verify.scenarios": "full",
			},
			nil,
		)
		if err != nil {
			return refused()
		}
		return sdk.Output{Capabilities: mutateCapabilities(capabilities)}
	case "generate":
		body, modelPath, writes := deterministicWrites(request)
		for _, entry := range writes {
			entryObject := entry.(map[string]any)
			if violation := sdk.WritePlanViolation(entryObject["path"].(string), a.writeScopes); violation != "" {
				return sdk.Output{Error: [3]string{"invalid", "write-refused", "the write plan left the declared output scope: " + violation}, HasError: true}
			}
		}
		if dryRun, _ := sdk.GetBool(request, "dry_run"); !dryRun || fault("mutate-dry") {
			_ = os.MkdirAll(filepath.Dir(modelPath), 0o755)
			// The injected dry-run mutation must never normalize to a clean
			// pass (issue #106 review r3 #1): when the host's confinement
			// sandbox refuses the write, the fault surfaces as a failed
			// exchange, never a silent success.
			if err := os.WriteFile(modelPath, []byte(body), 0o644); err != nil {
				return sdk.Output{Error: [3]string{"invalid", "dry-run-mutation-refused", "the injected dry-run mutation was refused by the confinement sandbox"}, HasError: true}
			}
		}
		if dryRun, _ := sdk.GetBool(request, "dry_run"); fault("extra-write") && !dryRun {
			_ = os.WriteFile(filepath.Join(filepath.Dir(modelPath), "extra.txt"), []byte("undeclared"), 0o644)
		}
		planID := sdk.GetString(request, "plan_id")
		if planID == "" {
			planID = planIDOf(writes)
		}
		return sdk.Output{
			PlanID: planID,
			Progress: []any{
				map[string]any{"state": "done", "step": "compile"},
				map[string]any{"state": "done", "step": "emit"},
			},
			Writes: writes,
		}
	case "plan-clean":
		_, _, writes := deterministicWrites(request)
		plan := make([]any, 0, len(writes))
		for _, entry := range writes {
			entryObject := entry.(map[string]any)
			plan = append(plan, map[string]any{"action": "delete", "path": entryObject["path"]})
		}
		return sdk.Output{PlanID: planIDOf(plan), Writes: plan}
	case "plan-native":
		return sdk.Output{Error: [3]string{"unsupported", "plan-native-unsupported", "this reference adapter does not plan native gates"}, HasError: true}
	case "scan":
		return sdk.Output{Payload: map[string]any{
			"entries": []any{
				map[string]any{"kind": "source", "path": "src/main.ts"},
				map[string]any{"kind": "source", "path": "src/util.ts"},
			},
			"truncated": false,
		}}
	case "validate", "verify":
		return sdk.Output{Payload: map[string]any{"findings": []any{}, "ok": true}}
	default:
		return sdk.Output{Error: [3]string{"unsupported", "operation-unsupported", "the operation is not implemented by this adapter"}, HasError: true}
	}
}

func refused() sdk.Output {
	return sdk.Output{Error: [3]string{"infrastructure", "sdk-build-refused", "the capability builder refused the declaration"}, HasError: true}
}

func main() {
	// Hostile pre-serve faults (issue #106 review r3 #1/#2): crash
	// refuses the handshake with a nonzero exit, garbage pollutes the
	// wire surface, hang never responds (deadline enforcement), and
	// noise trips the stderr bounds. All are no-ops cooperatively.
	if fault("crash") {
		os.Exit(3)
	}
	if fault("garbage") {
		_, _ = os.Stdout.WriteString("<this is not json>")
		os.Exit(0)
	}
	if fault("hang") {
		time.Sleep(60 * time.Second)
		os.Exit(0)
	}
	if fault("noise") {
		_, _ = os.Stderr.WriteString(strings.Repeat("x", 2_000_000))
	}
	identity, err := sdk.BuildAdapterIdentity(adapterID, "0.1.0", sdk.Sha256("lekalo adapter-sdk reference adapter"))
	if err != nil {
		os.Exit(1)
	}
	os.Exit(sdk.Serve(&referenceAdapter{
		identity:    identity,
		writeScopes: []string{writeRoot + "/" + adapterID + "/**"},
	}))
}
