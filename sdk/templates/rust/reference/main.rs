//! The SDK reference adapter (issue #106): the complete strict base
//! surface implemented entirely on `lekalo-adapter-sdk-rust`, equivalent
//! to the handwritten fake-adapter control but with every wire byte
//! built, validated, and emitted by the SDK runtime. Deterministic: the
//! same request always produces the same plan and the same bytes.

use lekalo_adapter_sdk as sdk;
use sdk::{Adapter, Output, Value};
use std::io::Write;

const ADAPTER_ID: &str = "sdk-reference";
const WRITE_ROOT: &str = ".lekalo/generated";

/// Hostile-mode fault knobs (issue #106 review r3 #1/#2): the same
/// closed vocabulary as the handwritten fake-adapter control (crash,
/// garbage, hang, noise, mutate-dry, extra-write), so the lifecycle
/// lanes drive the hostile classes against the real SDK serve loop. A
/// run without --lekalo-fault is fully cooperative.
fn fault(name: &str) -> bool {
    let argv = std::env::args().collect::<Vec<_>>();
    let value = argv
        .iter()
        .position(|argument| argument == "--lekalo-fault")
        .and_then(|index| argv.get(index + 1))
        .cloned()
        .unwrap_or_default();
    value.split(',').any(|candidate| candidate == name)
}

fn member_of(value: &Value, key: &str) -> Value {
    value.get(key).cloned().unwrap_or(Value::Null)
}

// In-serve fault helpers (issue #106 review r4 #7): callback-crash makes
// the real handler fail (the SDK serve loop answers with a closed error
// envelope — the callback-failure contract), callback-hang stalls inside
// the handler past every deadline (host termination while the serve
// loop is live), and log-verbose floods the bounded SDK logger from
// inside the handler (a verbose run must still pass).
fn callback_faults(operation: &str) -> Option<Output> {
    if fault("log-verbose") {
        for index in 0..200 {
            sdk::logger::error(
                ADAPTER_ID,
                &format!("verbose lifecycle tick {index} ({operation})"),
            );
        }
    }
    if fault("callback-hang") {
        std::thread::sleep(std::time::Duration::from_secs(60));
    }
    if fault("callback-crash") {
        return Some(error_output(
            "infrastructure",
            "callback-crashed",
            "the callback failed inside the SDK serve loop".to_owned(),
        ));
    }
    None
}

struct ReferenceAdapter {
    identity: Value,
    write_scopes: Vec<String>,
    write_scope_refs: Vec<&'static str>,
}

fn deterministic_writes(request: &Value) -> (String, String, Vec<Value>) {
    let target_value = member_of(request, "target");
    let target = match target_value.as_str() {
        Some(value) if !value.is_empty() => value.to_owned(),
        _ => ADAPTER_ID.to_owned(),
    };
    let profile = member_of(request, "profile").as_str().unwrap_or("default").to_owned();
    let ir_path = member_of(request, "ir_path").as_str().unwrap_or(".lekalo/ir/planner.json").to_owned();
    let body = format!(
        "// generated by {ADAPTER_ID}@0.1.0\n// target: {target}\n// profile: {profile}\n// ir: {ir_path}\n"
    );
    let path = format!("{WRITE_ROOT}/{ADAPTER_ID}/model.ts");
    let digest = sdk::write_entry_digest(&body);
    let writes = vec![sdk::Value::Object(vec![
        ("action".to_owned(), Value::Str("create".to_owned())),
        ("path".to_owned(), Value::Str(path)),
        ("sha256".to_owned(), Value::Str(digest)),
    ])];
    (body, format!("{WRITE_ROOT}/{ADAPTER_ID}/model.ts"), writes)
}

fn plan_id_of(writes: &[Value]) -> String {
    let value = Value::Array(writes.to_vec());
    sdk::plan_id(&value)
}

impl Adapter for ReferenceAdapter {
    fn identity(&self) -> Value {
        self.identity.clone()
    }

    fn handle(&self, operation: &str, request: &Value) -> Output {
        if let Some(failed) = callback_faults(operation) {
            return failed;
        }
        match operation {
            "bind" => Output {
                payload: Some(Value::Object(vec![(
                    "bindings".to_owned(),
                    Value::Array(vec![Value::Object(vec![
                        ("module".to_owned(), Value::Str("planner".to_owned())),
                        ("profile".to_owned(), member_of(request, "profile")),
                        ("target".to_owned(), member_of(request, "target")),
                    ])]),
                )])),
                ..Output::default()
            },
            "clean" => {
                let (_, _, writes) = deterministic_writes(request);
                let plan: Vec<Value> = writes
                    .iter()
                    .map(|entry| {
                        Value::Object(vec![
                            ("action".to_owned(), Value::Str("delete".to_owned())),
                            ("path".to_owned(), entry.get("path").cloned().unwrap_or(Value::Null)),
                        ])
                    })
                    .collect();
                for entry in &plan {
                    let path = entry.get("path").and_then(Value::as_str).unwrap_or("");
                    let _ = std::fs::remove_file(path);
                }
                Output {
                    plan_id: Some(
                        member_of(request, "plan_id").as_str().map(str::to_owned).unwrap_or_else(|| plan_id_of(&plan)),
                    ),
                    writes: Some(Value::Array(plan)),
                    ..Output::default()
                }
            }
            "describe" => {
                let capabilities = sdk::build_capabilities(
                    &self.identity,
                    &["0.3.2"],
                    &["bind", "clean", "describe", "generate", "plan-clean", "plan-native", "scan", "validate", "verify"],
                    &["file", "stdin"],
                    &[ADAPTER_ID],
                    &[],
                    &[".lekalo/ir/**", ".lekalo/cache/ir/**"],
                    &self.write_scope_refs,
                    &["0.2.16"],
                    true,
                    Some(vec![
                        ("generate.openapi", "partial"),
                        ("generate.ui", "unsupported"),
                        ("generate.zod", "full"),
                        ("scan.symbols", "full"),
                        ("verify.scenarios", "full"),
                    ]),
                    None,
                );
                match capabilities {
                    Ok(value) => Output { capabilities: Some(value), ..Output::default() },
                    Err(_) => refused(),
                }
            }
            "generate" => {
                let (body, model_path, writes) = deterministic_writes(request);
                for entry in &writes {
                    let path = entry.get("path").and_then(Value::as_str).unwrap_or("");
                    if let Some(violation) = sdk::write_plan_violation(path, &self.write_scopes) {
                        return error_output(
                            "invalid",
                            "write-refused",
                            format!("the write plan left the declared output scope: {violation}"),
                        );
                    }
                }
                if member_of(request, "dry_run").as_bool() == Some(false) || fault("mutate-dry") {
                    if let Some(parent) = std::path::Path::new(&model_path).parent() {
                        let _ = std::fs::create_dir_all(parent);
                    }
                    let written = std::fs::File::create(&model_path)
                        .and_then(|mut file| file.write_all(body.as_bytes()));
                    // The injected dry-run mutation must never normalize to a
                    // clean pass (issue #106 review r3 #1): when the host's
                    // confinement sandbox refuses the write, the fault surfaces
                    // as a failed exchange, never a silent success.
                    if written.is_err() {
                        return error_output(
                            "invalid",
                            "dry-run-mutation-refused",
                            "the injected dry-run mutation was refused by the confinement sandbox".to_owned(),
                        );
                    }
                }
                if fault("extra-write") && member_of(request, "dry_run").as_bool() == Some(false) {
                    if let Some(parent) = std::path::Path::new(&model_path).parent() {
                        let extra = parent.join("extra.txt");
                        let _ = std::fs::File::create(&extra).and_then(|mut file| file.write_all(b"undeclared"));
                    }
                }
                Output {
                    plan_id: Some(
                        member_of(request, "plan_id").as_str().map(str::to_owned).unwrap_or_else(|| plan_id_of(&writes)),
                    ),
                    progress: Some(Value::Array(vec![
                        Value::Object(vec![
                            ("state".to_owned(), Value::Str("done".to_owned())),
                            ("step".to_owned(), Value::Str("compile".to_owned())),
                        ]),
                        Value::Object(vec![
                            ("state".to_owned(), Value::Str("done".to_owned())),
                            ("step".to_owned(), Value::Str("emit".to_owned())),
                        ]),
                    ])),
                    writes: Some(Value::Array(writes)),
                    ..Output::default()
                }
            }
            "plan-clean" => {
                let (_, _, writes) = deterministic_writes(request);
                let plan: Vec<Value> = writes
                    .iter()
                    .map(|entry| {
                        Value::Object(vec![
                            ("action".to_owned(), Value::Str("delete".to_owned())),
                            ("path".to_owned(), entry.get("path").cloned().unwrap_or(Value::Null)),
                        ])
                    })
                    .collect();
                Output {
                    plan_id: Some(plan_id_of(&plan)),
                    writes: Some(Value::Array(plan)),
                    ..Output::default()
                }
            }
            "plan-native" => error_output(
                "unsupported",
                "plan-native-unsupported",
                "this reference adapter does not plan native gates".to_owned(),
            ),
            "scan" => Output {
                payload: Some(Value::Object(vec![
                    (
                        "entries".to_owned(),
                        Value::Array(vec![
                            Value::Object(vec![
                                ("kind".to_owned(), Value::Str("source".to_owned())),
                                ("path".to_owned(), Value::Str("src/main.ts".to_owned())),
                            ]),
                            Value::Object(vec![
                                ("kind".to_owned(), Value::Str("source".to_owned())),
                                ("path".to_owned(), Value::Str("src/util.ts".to_owned())),
                            ]),
                        ]),
                    ),
                    ("truncated".to_owned(), Value::Bool(false)),
                ])),
                ..Output::default()
            },
            "validate" | "verify" => Output {
                payload: Some(Value::Object(vec![
                    ("findings".to_owned(), Value::Array(vec![])),
                    ("ok".to_owned(), Value::Bool(true)),
                ])),
                ..Output::default()
            },
            _ => error_output("unsupported", "operation-unsupported", "the operation is not implemented by this adapter".to_owned()),
        }
    }
}

fn refused() -> Output {
    error_output("infrastructure", "sdk-build-refused", "the capability builder refused the declaration".to_owned())
}
fn error_output(class: &'static str, code: &'static str, message: String) -> Output {
    Output {
        error: Some((class, code, message)),
        ..Output::default()
    }
}

fn main() {
    // Hostile pre-serve faults (issue #106 review r3 #1/#2): crash
    // refuses the handshake with a nonzero exit, garbage pollutes the
    // wire surface, hang never responds (deadline enforcement), and
    // noise trips the stderr bounds. All are no-ops cooperatively.
    if fault("crash") {
        std::process::exit(3);
    }
    if fault("garbage") {
        let _ = std::io::stdout().write_all(b"<this is not json>");
        std::process::exit(0);
    }
    if fault("hang") {
        std::thread::sleep(std::time::Duration::from_secs(60));
        std::process::exit(0);
    }
    if fault("noise") {
        let _ = std::io::stderr().write_all(&vec![b'x'; 2_000_000]);
    }
    let identity = sdk::build_adapter_identity(
        ADAPTER_ID,
        "0.1.0",
        &sdk::sha256("lekalo adapter-sdk reference adapter"),
    )
    .expect("identity admits");
    let write_scope = format!("{WRITE_ROOT}/{ADAPTER_ID}/**");
    // The borrowed scope view lives as long as the adapter (static promotion
    // through a leak is unnecessary: one owned String, one borrowed slice).
    let write_scope_static: &'static str = Box::leak(write_scope.into_boxed_str());
    let adapter = ReferenceAdapter {
        identity,
        write_scopes: vec![write_scope_static.to_owned()],
        write_scope_refs: vec![write_scope_static],
    };
    std::process::exit(sdk::serve(&adapter));
}
