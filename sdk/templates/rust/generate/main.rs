//! The SDK generate example (issue #106): a generation adapter on
//! `lekalo-adapter-sdk-rust` that opts into one narrow output scope,
//! plans before apply, computes dry-run byte digests without writing,
//! and echoes the host's plan authority on apply. Read-only by default.

use lekalo_adapter_sdk as sdk;
use sdk::{Adapter, Output, Value};
use std::io::Write;

const ADAPTER_ID: &str = "sdk-generate-example";
const WRITE_ROOT: &str = ".lekalo/generated";

struct GenerateAdapter {
    identity: Value,
    write_scope: &'static str,
}

fn deterministic_writes(request: &Value) -> (String, String, Vec<Value>) {
    let target = match member_of(request, "target").as_str() {
        Some(value) if !value.is_empty() => value.to_owned(),
        _ => ADAPTER_ID.to_owned(),
    };
    let profile = match member_of(request, "profile").as_str() {
        Some(value) if !value.is_empty() => value.to_owned(),
        _ => "default".to_owned(),
    };
    let ir_path = match member_of(request, "ir_path").as_str() {
        Some(value) if !value.is_empty() => value.to_owned(),
        _ => ".lekalo/ir/planner.json".to_owned(),
    };
    let body = format!(
        "// generated by {ADAPTER_ID}@0.1.0\n// target: {target}\n// profile: {profile}\n// ir: {ir_path}\n"
    );
    let digest = sdk::write_entry_digest(&body);
    let writes = vec![Value::Object(vec![
        ("action".to_owned(), Value::Str("create".to_owned())),
        ("path".to_owned(), Value::Str(format!("{WRITE_ROOT}/{ADAPTER_ID}/model.ts"))),
        ("sha256".to_owned(), Value::Str(digest)),
    ])];
    (body, format!("{WRITE_ROOT}/{ADAPTER_ID}/model.ts"), writes)
}

fn member_of(value: &Value, key: &str) -> Value {
    value.get(key).cloned().unwrap_or(Value::Null)
}

impl Adapter for GenerateAdapter {
    fn identity(&self) -> Value {
        self.identity.clone()
    }

    fn handle(&self, operation: &str, request: &Value) -> Output {
        match operation {
            "describe" => match sdk::build_capabilities(
                &self.identity,
                &["0.3.2"],
                &["describe", "generate", "plan-clean"],
                &["file", "stdin"],
                &[ADAPTER_ID],
                &[],
                &[".lekalo/ir/**"],
                &[self.write_scope],
                &["0.2.16"],
                true,
                Some(vec![("generate.zod", "full")]),
                None,
            ) {
                Ok(value) => Output { capabilities: Some(value), ..Output::default() },
                Err(_) => refused(),
            },
            "generate" => {
                let (body, model_path, writes) = deterministic_writes(request);
                for entry in &writes {
                    let path = entry.get("path").and_then(Value::as_str).unwrap_or("");
                    if let Some(violation) = sdk::write_plan_violation(path, &[self.write_scope.to_owned()]) {
                        return Output {
                            error: Some((
                                "invalid",
                                "write-refused",
                                format!("the write plan left the declared output scope: {violation}"),
                            )),
                            ..Output::default()
                        };
                    }
                }
                if member_of(request, "dry_run").as_bool() == Some(false) {
                    if let Some(parent) = std::path::Path::new(&model_path).parent() {
                        let _ = std::fs::create_dir_all(parent);
                    }
                    if let Ok(mut file) = std::fs::File::create(&model_path) {
                        let _ = file.write_all(body.as_bytes());
                    }
                }
                let plan = member_of(request, "plan_id")
                    .as_str()
                    .map(str::to_owned)
                    .unwrap_or_else(|| sdk::canonical_plan_id(&sdk::sort_write_plan(&Value::Array(writes.clone())).unwrap_or_default()));
                Output {
                    plan_id: Some(plan),
                    progress: Some(Value::Array(vec![Value::Object(vec![
                        ("state".to_owned(), Value::Str("done".to_owned())),
                        ("step".to_owned(), Value::Str("emit".to_owned())),
                    ])])),
                    writes: Some(Value::Array(writes)),
                    ..Output::default()
                }
            }
            "plan-clean" => {
                let (_, _, writes) = deterministic_writes(request);
                let plan: Vec<Value> = writes
                    .iter()
                    .map(|entry| {
                        Value::Object(vec![
                            ("action".to_owned(), Value::Str("delete".to_owned())),
                            ("path".to_owned(), entry.get("path").cloned().unwrap_or(Value::Null)),
                        ])
                    })
                    .collect();
                Output {
                    plan_id: Some(sdk::canonical_plan_id(&sdk::sort_write_plan(&Value::Array(plan.clone())).unwrap_or_default())),
                    writes: Some(Value::Array(plan)),
                    ..Output::default()
                }
            }
            _ => Output {
                error: Some((
                    "unsupported",
                    "operation-unsupported",
                    "the generate example implements describe, generate, and plan-clean only".to_owned(),
                )),
                ..Output::default()
            },
        }
    }
}

fn refused() -> Output {
    Output {
        error: Some((
            "infrastructure",
            "sdk-build-refused",
            "the capability builder refused the declaration".to_owned(),
        )),
        ..Output::default()
    }
}

fn main() {
    let identity = sdk::build_adapter_identity(
        ADAPTER_ID,
        "0.1.0",
        &sdk::sha256("lekalo adapter-sdk generate example"),
    )
    .expect("identity admits");
    let write_scope: &'static str = Box::leak(format!("{WRITE_ROOT}/{ADAPTER_ID}/**").into_boxed_str());
    std::process::exit(sdk::serve(&GenerateAdapter { identity, write_scope }));
}
