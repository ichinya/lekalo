<?php
// The SDK reference adapter (issue #106): the complete strict base
// surface implemented entirely on the PHP adapter SDK, equivalent to
// the handwritten fake-adapter control but with every wire byte built,
// validated, and emitted by the SDK runtime. Deterministic.

declare(strict_types=1);

use Lekalo\AdapterSdk\Runtime\Build;
use Lekalo\AdapterSdk\Runtime\Canonical;
use Lekalo\AdapterSdk\Runtime\Ids;
use Lekalo\AdapterSdk\Runtime\Paths;
use Lekalo\AdapterSdk\Runtime\Serve;

const WRITE_ROOT = '.lekalo/generated';
const ADAPTER_ID = 'sdk-reference';

// Hostile-mode fault knobs (issue #106 review r3 #1/#2): the same closed
// vocabulary as the handwritten fake-adapter control (crash, garbage,
// hang, noise, mutate-dry, extra-write), so the lifecycle lanes drive
// the hostile classes against the real SDK serve loop. A run without
// --lekalo-fault is fully cooperative.
$FAULT_ARG = array_search('--lekalo-fault', $_SERVER['argv'], true);
$FAULT = is_int($FAULT_ARG) && isset($_SERVER['argv'][$FAULT_ARG + 1]) ? $_SERVER['argv'][$FAULT_ARG + 1] : '';
function fault(string $name): bool {
    global $FAULT;
    return in_array($name, explode(',', $FAULT), true);
}
if (fault('crash')) {
    exit(3);
}
if (fault('garbage')) {
    fwrite(STDOUT, '<this is not json>');
    exit(0);
}
if (fault('hang')) {
    sleep(60);
    exit(0);
}
if (fault('noise')) {
    fwrite(STDERR, str_repeat('x', 2_000_000));
}

$identity = Build::buildAdapterIdentity(ADAPTER_ID, '0.1.0', Ids::sha256('lekalo adapter-sdk reference adapter'));
$writeScopes = [WRITE_ROOT . '/' . ADAPTER_ID . '/**'];
$capabilitiesMap = [
    'generate.openapi' => 'partial',
    'generate.ui' => 'unsupported',
    'generate.zod' => 'full',
    'scan.symbols' => 'full',
    'verify.scenarios' => 'full',
];

// Deliberately invalid completed callback output for serve-level probes.
function mutateCapabilities(array $caps): array {
    foreach (['operations', 'protocol_versions', 'transports'] as $member) {
        if (fault("invalid-{$member}")) $caps[$member] = [];
    }
    foreach (['max_entries', 'max_writes'] as $member) {
        if (fault("invalid-{$member}")) $caps['constraints'] = [$member => 0];
    }
    if (fault('invalid-capability')) $caps['capabilities'] = ['not.a.real.capability' => 'full'];
    if (fault('invalid-identity')) $caps['adapter']['id'] = 'foreign-adapter';
    if (fault('invalid-negotiation')) $caps['protocol_versions'] = ['9.9.9'];
    if (fault('invalid-describe')) $caps['operations'] = ['scan'];
    return $caps;
}

function deterministicWrites(array $request): array {
    $target = $request['target'] ?? ADAPTER_ID;
    $profile = $request['profile'] ?? 'default';
    $irPath = $request['ir_path'] ?? '.lekalo/ir/planner.json';
    $body = "// generated by " . ADAPTER_ID . "@0.1.0\n// target: {$target}\n// profile: {$profile}\n// ir: {$irPath}\n";
    $path = WRITE_ROOT . '/' . ADAPTER_ID . '/model.ts';
    $writes = Canonical::sortWritePlan([['action' => 'create', 'path' => $path, 'sha256' => Canonical::writeEntryDigest($body)]]);
    return ['body' => $body, 'modelPath' => $path, 'writes' => $writes];
}

function planIdOf(array $writes): string {
    return Canonical::canonicalPlanId($writes);
}

// Honest error-return and real exception lanes exercise distinct outcomes.
// callback-error returns a closed error; handler-crash throws inside the
// real handler and the runtime refuses with nonzero exit. callback-hang stalls inside
// the handler past every deadline (host termination while the serve loop
// is live), and log-verbose floods the bounded SDK logger from inside
// the handler (a verbose run must still pass).
function callbackFaults(string $operation): ?array {
    if (fault('log-verbose')) {
        for ($index = 0; $index < 200; $index++) {
            Logger::error(ADAPTER_ID, "verbose lifecycle tick {$index} ({$operation})");
        }
    }
    if (fault('callback-hang')) {
        sleep(60);
    }
    if (fault('handler-crash')) {
        throw new \RuntimeException('callback exploded inside the SDK serve loop');
    }
    if (fault('callback-error')) {
        return ['error' => ['errorClass' => 'infrastructure', 'errorCode' => 'callback-error', 'message' => 'the handler deliberately refused']];
    }
    return null;
}

$handlers = [
    'bind' => function (array $request) {
        return ['payload' => ['bindings' => [['module' => 'planner', 'profile' => $request['profile'], 'target' => $request['target']]]]];
    },
    'clean' => function (array $request) use ($writeScopes) {
        $deterministic = deterministicWrites($request);
        $plan = Canonical::sortWritePlan(array_map(fn ($entry) => ['action' => 'delete', 'path' => $entry['path']], $deterministic['writes']));
        foreach ($plan as $entry) {
            if (file_exists($entry['path'])) {
                @unlink($entry['path']);
            }
        }
        return ['planId' => $request['plan_id'] ?? planIdOf($plan), 'writes' => $plan];
    },
    'describe' => function (array $request) use ($identity, $capabilitiesMap, $writeScopes) {
        $failed = callbackFaults('describe');
        if ($failed !== null) {
            return $failed;
        }
        $caps = Build::buildCapabilities(
            $identity,
            ['0.3.2'],
            ['bind', 'clean', 'describe', 'generate', 'plan-clean', 'plan-native', 'scan', 'validate', 'verify'],
            ['file', 'stdin'],
            [ADAPTER_ID],
            [],
            ['.lekalo/ir/**', '.lekalo/cache/ir/**'],
            $writeScopes,
            ['0.2.16'],
            true,
            $capabilitiesMap
        );
        if (fault('limits-probe')) {
            // PHP callbacks consume the accepted deadline via named limits.
            $caps['constraints'] = ['max_entries' => $request['limits']['timeout_ms'] ?? null, 'max_writes' => $request['limits']['max_output_bytes'] ?? null];
        }
        return mutateCapabilities($caps);
    },
    'generate' => function (array $request) use ($writeScopes) {
        $failed = callbackFaults('generate');
        if ($failed !== null) {
            return $failed;
        }
        $deterministic = deterministicWrites($request);
        foreach ($deterministic['writes'] as $entry) {
            $violation = Canonical::writePlanViolation($entry['path'], $writeScopes);
            if ($violation !== null) {
                return ['error' => ['errorClass' => 'invalid', 'errorCode' => 'write-refused', 'message' => "the write plan left the declared output scope: {$violation}"]];
            }
        }
        if (($request['dry_run'] ?? null) === false || fault('mutate-dry')) {
            @mkdir(dirname($deterministic['modelPath']), 0777, true);
            // The injected dry-run mutation must never normalize to a clean
            // pass (issue #106 review r3 #1): when the host's confinement
            // sandbox refuses the write, the fault surfaces as a failed
            // exchange, never a silent success.
            if (@file_put_contents($deterministic['modelPath'], $deterministic['body']) === false) {
                return ['error' => ['errorClass' => 'invalid', 'errorCode' => 'dry-run-mutation-refused', 'message' => 'the injected dry-run mutation was refused by the confinement sandbox']];
            }
        }
        if (fault('extra-write') && ($request['dry_run'] ?? null) === false) {
            file_put_contents(dirname($deterministic['modelPath']) . '/extra.txt', 'undeclared');
        }
        return [
            'planId' => $request['plan_id'] ?? planIdOf($deterministic['writes']),
            'progress' => [['state' => 'done', 'step' => 'compile'], ['state' => 'done', 'step' => 'emit']],
            'writes' => $deterministic['writes'],
        ];
    },
    'plan-clean' => function () use ($writeScopes) {
        $deterministic = deterministicWrites(['target' => ADAPTER_ID, 'profile' => 'default', 'ir_path' => '.lekalo/ir/planner.json']);
        $plan = Canonical::sortWritePlan(array_map(fn ($entry) => ['action' => 'delete', 'path' => $entry['path']], $deterministic['writes']));
        return ['planId' => planIdOf($plan), 'writes' => $plan];
    },
    'plan-native' => function () {
        // r10: mutate callback output, not the emission validator.
        if (fault('native-plan-control') || fault('invalid-native-entries') || fault('invalid-native-units')) {
            $plan = ['kind' => 'native-plan', 'digest' => Ids::sha256('native-plan-control'), 'commands' => 2, 'packages' => 1, 'completeness' => 'complete', 'run_eligibility' => 'runnable'];
            foreach (['entries', 'units'] as $member) {
                if (fault("invalid-native-{$member}")) $plan[$member] = 1;
            }
            return ['payload' => ['native_plan' => $plan]];
        }
        return ['error' => ['errorClass' => 'unsupported', 'errorCode' => 'plan-native-unsupported', 'message' => 'this reference adapter does not plan native gates']];
    },
    'scan' => function () {
        return ['payload' => ['entries' => [['kind' => 'source', 'path' => 'src/main.ts'], ['kind' => 'source', 'path' => 'src/util.ts']], 'truncated' => false]];
    },
    'validate' => function () {
        return ['payload' => ['findings' => [], 'ok' => true]];
    },
    'verify' => function () {
        return ['payload' => ['findings' => [], 'ok' => true]];
    },
];

exit(Serve::serve(['identity' => $identity, 'handlers' => $handlers]));
