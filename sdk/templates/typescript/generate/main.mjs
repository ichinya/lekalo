/**
 * The SDK generate example (issue #106): a generation adapter on
 * `@lekalo/adapter-sdk` that opts into one narrow output scope, plans
 * before apply, computes dry-run byte digests without writing, and
 * echoes the host's plan authority on apply. Read-only by default;
 * writes stay inside the declared scope; no network, no shell.
 */
import { buildAdapterIdentity, buildCapabilities } from "../../../typescript/src/runtime/build.mjs";
import { canonicalPlanId, sortWritePlan, writeEntryDigest, writePlanViolation } from "../../../typescript/src/runtime/canonical.mjs";
import { sha256 } from "../../../typescript/src/runtime/ids.mjs";
import { serve } from "../../../typescript/src/runtime/serve.mjs";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const IDENTITY = buildAdapterIdentity({
  digest: sha256("lekalo adapter-sdk generate example"),
  id: "sdk-generate-example",
  version: "0.1.0",
});
const WRITE_ROOT = ".lekalo/generated";

function deterministicWrites(request) {
  const target = request.target ?? "sdk-generate-example";
  const profile = request.profile ?? "default";
  const irPath = request.ir_path ?? ".lekalo/ir/planner.json";
  const body = `// generated by ${IDENTITY.id}@${IDENTITY.version}\n// target: ${target}\n// profile: ${profile}\n// ir: ${irPath}\n`;
  const path = `${WRITE_ROOT}/${IDENTITY.id}/model.ts`;
  return { body, modelPath: path, writes: sortWritePlan([{ action: "create", path, sha256: writeEntryDigest(body) }]) };
}

const WRITE_SCOPES = [`${WRITE_ROOT}/${IDENTITY.id}/**`];

// The bounded serve loop returns the process exit code: refusal classes
// (malformed input, oversize, output-limit, …) must surface as nonzero
// process status (issue #106 review r2 #7).
process.exitCode = await serve({
  handlers: {
    async describe() {
      return buildCapabilities({
        adapter: IDENTITY,
        capabilities: { "generate.zod": "full" },
        irVersions: ["0.2.16"],
        operations: ["describe", "generate", "plan-clean"],
        progress: true,
        protocolVersions: ["0.3.2"],
        readScopes: [".lekalo/ir/**"],
        targets: ["sdk-generate-example"],
        transports: ["stdin", "file"],
        writeScopes: WRITE_SCOPES,
      });
    },
    async generate({ request }) {
      const { body, modelPath, writes } = deterministicWrites(request);
      for (const entry of writes) {
        const violation = writePlanViolation(entry, WRITE_SCOPES);
        if (violation !== null) {
          return {
            error: {
              errorClass: "invalid",
              errorCode: "write-refused",
              message: `the write plan left the declared output scope: ${violation}`,
            },
          };
        }
      }
      if (request.dry_run === false) {
        mkdirSync(dirname(modelPath), { recursive: true });
        writeFileSync(modelPath, body);
      }
      return {
        planId: request.plan_id ?? canonicalPlanId(writes),
        progress: [{ state: "done", step: "emit" }],
        writes,
      };
    },
    async planClean() {
      const { writes } = deterministicWrites({ target: "sdk-generate-example", profile: "default", ir_path: ".lekalo/ir/planner.json" });
      const plan = sortWritePlan(writes.map(({ path }) => ({ action: "delete", path })));
      return { planId: canonicalPlanId(plan), writes: plan };
    },
  },
  identity: IDENTITY,
});

