/**
 * The SDK reference adapter (issue #106): the complete strict base
 * surface implemented entirely on `@lekalo/adapter-sdk`, equivalent to
 * the handwritten fake-adapter control but with every wire byte built,
 * validated, and emitted by the SDK runtime. Deterministic: the same
 * request always produces the same plan and the same bytes.
 */
import { buildAdapterIdentity, buildCapabilities } from "../../../typescript/src/runtime/build.mjs";
import { canonicalPlanId, sortWritePlan, writeEntryDigest, writePlanViolation } from "../../../typescript/src/runtime/canonical.mjs";
import { sha256 } from "../../../typescript/src/runtime/ids.mjs";
import { serve } from "../../../typescript/src/runtime/serve.mjs";
import { mkdirSync, writeFileSync, existsSync, rmSync } from "node:fs";
import { dirname } from "node:path";

const IDENTITY = buildAdapterIdentity({
  digest: sha256("lekalo adapter-sdk reference adapter"),
  id: "sdk-reference",
  version: "0.1.0",
});
const WRITE_ROOT = ".lekalo/generated";

// Hostile-mode fault knobs (issue #106 review r3 #1/#2): the same closed
// vocabulary as the handwritten fake-adapter control (crash, garbage,
// hang, noise, mutate-dry, extra-write), so the lifecycle lanes drive
// the hostile classes against the real SDK serve loop — a faulted SDK
// adapter must fail its recipe exactly like the control does. A run
// without --lekalo-fault is fully cooperative.
//
// In-serve knobs (issue #106 review r4 #7): callback-crash throws inside
// the real handler (the SDK serve loop must answer with a closed error
// envelope, never a crash), callback-hang stalls inside the handler past
// every deadline (host termination while the SDK serve loop is live),
// and log-verbose floods the bounded SDK logger from inside the handler
// (a verbose run must still pass). The pre-serve knobs remain for the
// host-termination classes they pin.
const FAULT_ARG = process.argv.indexOf("--lekalo-fault");
const FAULT = FAULT_ARG !== -1 && process.argv[FAULT_ARG + 1] ? process.argv[FAULT_ARG + 1] : "";
const fault = (name) => FAULT.split(",").includes(name);
const CALLBACK_CRASH = () => {
  if (fault("callback-crash")) throw new Error("callback exploded inside the SDK serve loop");
};
const AWAIT_CALLBACK_HANG = async () => {
  if (fault("callback-hang")) await new Promise((resolve) => setTimeout(resolve, 60_000));
};
const LOG_VERBOSE = (log) => {
  if (!fault("log-verbose")) return;
  for (let index = 0; index < 200; index += 1) log.error(`verbose lifecycle tick ${index}`);
};
if (fault("crash")) process.exit(3);
if (fault("garbage")) {
  process.stdout.write("<this is not json>");
  process.exit(0);
}
if (fault("hang")) {
  // Never respond: the host's deadline enforcement must terminate the
  // exchange (the battery classifies the timeout).
  await new Promise((resolve) => setTimeout(resolve, 60_000));
}
if (fault("noise")) {
  // Unbounded-class chatter on stderr: the battery's stderr bounds must
  // refuse the run instead of normalizing it.
  process.stderr.write("x".repeat(2_000_000));
}
const CAPABILITIES = {
  "generate.openapi": "partial",
  "generate.ui": "unsupported",
  "generate.zod": "full",
  "scan.symbols": "full",
  "verify.scenarios": "full",
};

function deterministicWrites(request) {
  const target = request.target ?? "sdk-reference";
  const profile = request.profile ?? "default";
  const irPath = request.ir_path ?? ".lekalo/ir/planner.json";
  const body = `// generated by ${IDENTITY.id}@${IDENTITY.version}\n// target: ${target}\n// profile: ${profile}\n// ir: ${irPath}\n`;
  const path = `${WRITE_ROOT}/${IDENTITY.id}/model.ts`;
  const writes = sortWritePlan([{ action: "create", path, sha256: writeEntryDigest(body) }]);
  return { body, modelPath: path, writes };
}

function planId(writes) {
  return canonicalPlanId(writes);
}

function assertWithinScopes(writes, scopes) {
  for (const entry of writes) {
    const violation = writePlanViolation(entry, scopes);
    if (violation !== null) {
      throw Object.assign(new Error(`write plan refused: ${violation}`), { reason: "write-refused" });
    }
  }
}

const WRITE_SCOPES = [`${WRITE_ROOT}/${IDENTITY.id}/**`];

// The bounded serve loop returns the process exit code: refusal classes
// (malformed input, oversize, output-limit, …) must surface as nonzero
// process status (issue #106 review r2 #7).
process.exitCode = await serve({
  handlers: {
    async clean({ request }) {
      const { writes } = deterministicWrites(request);
      const plan = sortWritePlan(writes.map(({ path }) => ({ action: "delete", path })));
      for (const entry of plan) {
        if (existsSync(entry.path)) rmSync(entry.path);
      }
      return { planId: request.plan_id ?? planId(plan), writes: plan };
    },
    async describe({ log }) {
      LOG_VERBOSE(log);
      await AWAIT_CALLBACK_HANG();
      CALLBACK_CRASH();
      return buildCapabilities({
        adapter: IDENTITY,
        capabilities: CAPABILITIES,
        irVersions: ["0.2.16"],
        operations: ["bind", "clean", "describe", "generate", "plan-clean", "plan-native", "scan", "validate", "verify"],
        progress: true,
        protocolVersions: ["0.3.2"],
        readScopes: [".lekalo/ir/**", ".lekalo/cache/ir/**"],
        targets: ["sdk-reference"],
        transports: ["stdin", "file"],
        writeScopes: WRITE_SCOPES,
      });
    },
    async generate({ log, request }) {
      LOG_VERBOSE(log);
      await AWAIT_CALLBACK_HANG();
      CALLBACK_CRASH();
      const { body, modelPath, writes } = deterministicWrites(request);
      assertWithinScopes(writes, WRITE_SCOPES);
      if (request.dry_run === false || fault("mutate-dry")) {
        mkdirSync(dirname(modelPath), { recursive: true });
        writeFileSync(modelPath, body);
      }
      if (fault("extra-write") && request.dry_run === false) {
        writeFileSync(dirname(modelPath) + "/extra.txt", "undeclared");
      }
      return {
        planId: request.plan_id ?? planId(writes),
        progress: [
          { state: "done", step: "compile" },
          { state: "done", step: "emit" },
        ],
        writes,
      };
    },
    async "plan-clean"() {
      const { writes } = deterministicWrites({ target: "sdk-reference", profile: "default", ir_path: ".lekalo/ir/planner.json" });
      const plan = sortWritePlan(writes.map(({ path }) => ({ action: "delete", path })));
      return { planId: planId(plan), writes: plan };
    },
    async "plan-native"() {
      return {
        error: {
          errorClass: "unsupported",
          errorCode: "plan-native-unsupported",
          message: "this reference adapter does not plan native gates",
        },
      };
    },
    async scan() {
      return {
        payload: {
          entries: [
            { kind: "source", path: "src/main.ts" },
            { kind: "source", path: "src/util.ts" },
          ],
          truncated: false,
        },
      };
    },
    async bind({ request }) {
      return {
        payload: {
          bindings: [{ module: "planner", profile: request.profile, target: request.target }],
        },
      };
    },
    async validate() {
      return { payload: { findings: [], ok: true } };
    },
    async verify() {
      return { payload: { findings: [], ok: true } };
    },
  },
  identity: IDENTITY,
});

